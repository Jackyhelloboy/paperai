const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const front=fs.readFileSync('frontend/index.html','utf8');
const worker=fs.readFileSync('worker/src/index.js','utf8');
assert(front.includes('id="deepOcrVerify" checked'),'Teacher can select double-reading before uploading');
assert(front.includes("$('deepOcrVerify')?.checked===true"),'Each page forwards opt-in to the Worker');
assert(front.includes("'|deep-ocr-v1'"),'Deep-mode OCR checkpoints cannot reuse earlier single-read data');
assert(worker.includes('imageMeta?.deepVerify===true ||'),'Deep mode must run a second read even on a clear scan');
assert(worker.includes('second_read_completed:')&&worker.includes('verification_disagreement:'),'Worker exposes audit state');
assert(worker.includes('losesSourceQuestions(text,rescueText)')&&worker.includes('losesSourceMarks(text,rescueText)'),'Original questions and marks must be compared');
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync('worker/src/ocr-output-guard.js','utf8').replace(/export /g,''),ctx);
vm.runInContext(worker.slice(worker.indexOf('function shouldAcceptVerifiedText('),worker.indexOf('function mergeAiUsage(')),ctx);
const base='[[SECTION_ROW: I. प्रश्न लिखिए || 3M]]\n१. पहला प्रश्न\n२. दूसरा प्रश्न\n३. तीसरा प्रश्न';
const dropped=base.replace('२. दूसरा प्रश्न\n','');
assert(ctx.losesSourceQuestions(base,dropped));
assert(!ctx.shouldAcceptVerifiedText(base,dropped,{structuredLayout:true}),'Second AI must not silently lose a Hindi question');
assert(!ctx.shouldAcceptVerifiedText(base,base.replace('3M','4M'),{structuredLayout:true}),'Second AI must not change source marks');
console.log('Deep verification checks preserve original questions, marks and cache separation.');
